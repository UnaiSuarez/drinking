  id: string;
  nombre: string;
  rareza: CartaRareza;
  alcance: CartaAlcance;
  oculta?: boolean;
  /** Sin arte de IA todavía: se pinta con CartaArte usando `icono` de
   * respaldo. Las 36 cartas de noche originales siempre lo llevan. */
