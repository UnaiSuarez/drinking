import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

// Run against disposable PostgreSQL (PGlite), never the production database.
const modulePath = process.argv[2];
if (!modulePath) throw new Error('Pass the absolute PGlite module path');
const { PGlite } = await import(pathToFileURL(modulePath).href);
const db = new PGlite();
await db.exec(`
 create role anon; create role authenticated;
 create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.uid',true),'')::uuid$$;
 create table perfiles(id uuid primary key,nombre text,xp int default 0,avatar_config jsonb default '{}');
 create table salas(id uuid primary key,nombre text);
 create function public.es_miembro(uuid) returns boolean language sql as $$select false$$;
 create table temporadas(id uuid primary key,sala_id uuid references salas, nombre text,inicio timestamptz,fin timestamptz,estado text);
 create table liga(temporada_id uuid references temporadas,usuario_id uuid references perfiles,pl int,primary key(temporada_id,usuario_id));
 create table noches(id uuid primary key,temporada_id uuid references temporadas,inicio timestamptz,estado text);
 create table noche_jugadores(noche_id uuid references noches,usuario_id uuid references perfiles,pl_ganados int);
 insert into perfiles(id,nombre,xp) values ('00000000-0000-0000-0000-000000000001','A',50000),('00000000-0000-0000-0000-000000000002','B',0),('00000000-0000-0000-0000-000000000003','C',0);
 insert into salas values('00000000-0000-0000-0000-000000000010','Prueba');
 insert into temporadas values('00000000-0000-0000-0000-000000000020','00000000-0000-0000-0000-000000000010','Test',now()-interval '30 days',now(),'activa');
 insert into liga values('00000000-0000-0000-0000-000000000020','00000000-0000-0000-0000-000000000001',230);
`);
await db.exec(await readFile(path.resolve('supabase/migrations/20260927205503_liga_banners_recompensas.sql'),'utf8'));
await db.exec(await readFile(path.resolve('supabase/migrations/20260927214537_banners_ilustrados.sql'),'utf8'));
await db.exec(await readFile(path.resolve('supabase/migrations/20260927220758_banners_coleccion_dos.sql'),'utf8'));
await db.exec(`create table prestigios(usuario_id uuid references perfiles, ciclo int not null, primary key(usuario_id,ciclo));`);
await db.exec(`insert into prestigios values('00000000-0000-0000-0000-000000000001',1);`);
await db.exec(await readFile(path.resolve('supabase/migrations/20260927224058_banners_prestigio.sql'),'utf8'));
assert.equal((await db.query(`select banner_id from banners_usuario where usuario_id='00000000-0000-0000-0000-000000000001'`)).rows[0].banner_id,'primer-juramento','Existing prestige backfilled');
await db.exec(`insert into prestigios values('00000000-0000-0000-0000-000000000001',2),('00000000-0000-0000-0000-000000000002',1);`);
assert.equal((await db.query(`select count(*)::int as value from banners_usuario where banner_id in ('primer-juramento','guardian-esmeralda')`)).rows[0].value,3,'New prestige awards only its banner');
const scalar = async (sql) => (await db.query(sql)).rows[0].value;
assert.equal(await scalar('select count(*)::int as value from liga_premios'),0,'No retroactive payouts');
await db.exec('update liga set pl=450');
assert.equal(await scalar('select count(*)::int as value from liga_premios'),2,'Only new thresholds paid');
assert.equal(await scalar("select count(*)::int as value from banners_catalogo"),34);
assert.equal(await scalar("select count(*)::int as value from banners_usuario where banner_id='cumbre-after'"),1,'Grandmaster exclusive');
await db.exec('update liga set pl=0; update liga set pl=450;');
assert.equal(await scalar('select count(*)::int as value from liga_premios'),2,'No duplicate climbing');
assert.equal(await scalar(`select (avatar_config#>>'{inventario,cofres,legendario}')::int as value from perfiles where nombre='A'`),2);
await db.exec(`set request.uid='00000000-0000-0000-0000-000000000001'; select elegir_banner('circuito'); select elegir_banner('circuito');`);
assert.equal(await scalar(`select (avatar_config#>>'{tienda,gastadas}')::int as value from perfiles where nombre='A'`),90,'No double purchase');
await assert.rejects(db.exec(`select elegir_banner('campeon')`),/se gana/);
await assert.rejects(db.exec(`select elegir_banner('cenit')`),/se gana/);
await db.exec(`select elegir_banner('mesa-billar'); select elegir_banner('mesa-billar');`);
assert.equal(await scalar(`select (avatar_config#>>'{tienda,gastadas}')::int as value from perfiles where nombre='A'`),120,'New illustrated banner charged only once');
await db.exec(`set request.uid='00000000-0000-0000-0000-000000000002';`);
await assert.rejects(db.exec(`select elegir_banner('dragon')`),/suficientes chapas/);
await db.exec(`select elegir_banner('jade');`);
await db.exec(`set request.uid='';`);
await assert.rejects(db.exec(`select elegir_banner('jade')`),/No autenticado/);
await db.exec(`
 insert into liga values('00000000-0000-0000-0000-000000000020','00000000-0000-0000-0000-000000000002',60),('00000000-0000-0000-0000-000000000020','00000000-0000-0000-0000-000000000003',40);
 insert into noches select gen_random_uuid(),'00000000-0000-0000-0000-000000000020',now()-make_interval(days=>n),'cerrada' from generate_series(1,4) n;
 insert into noche_jugadores select n.id,p.id,10 from noches n cross join perfiles p;
 update temporadas set estado='cerrada';
`);
assert.equal(await scalar('select count(*)::int as value from liga_historial'),3);
assert.equal(await scalar(`select count(*)::int as value from banners_usuario where banner_id='campeon'`),1);
const payouts = await scalar('select count(*)::int as value from liga_premios');
await db.exec(`update temporadas set estado='activa'; update temporadas set estado='cerrada';`);
assert.equal(await scalar('select count(*)::int as value from liga_premios'),payouts,'Closing twice is idempotent');
await db.exec(`set role authenticated; set request.uid='00000000-0000-0000-0000-000000000002';`);
assert.equal(await scalar(`select count(*)::int as value from liga_historial`),1,'RLS hides unshared history');
await assert.rejects(db.exec(`select entregar_premio_liga(null,null,'hack','legendario',999)`),/permission denied/);
await assert.rejects(db.exec(`select entregar_banner_prestigio()`),/permission denied/);
await assert.rejects(db.exec(`insert into banners_usuario values('00000000-0000-0000-0000-000000000002','campeon',now())`),/permission denied/);
await db.close();
console.log('PASS: baseline, promotions, duplicate protection, purchases, exclusive lock, season rewards and RLS');
